from symsearch import search, cyc
def mob(a,b,c,dd,q):
    out=[]
    for x in range(q+1):
        if x==q: y= q if c%q==0 else (a*pow(c,-1,q))%q
        else:
            num=(a*x+b)%q; den=(c*x+dd)%q
            y= q if den==0 else num*pow(den,-1,q)%q
        out.append(y)
    return out
q=13
PSL213=[mob(1,1,0,1,q),mob(4,0,0,1,q),mob(0,q-1,1,0,q)]   # 4 is a square generator? squares mod 13 generated by 4 (order 6)
PGL213=PSL213+[mob(2,0,0,1,q)]
# Fano plane: points 0..6, lines L_i={i,i+1,i+3} mod 7 -> labeled 7..13
lines=[{i%7,(i+1)%7,(i+3)%7} for i in range(7)]
def fano_perm(pp):  # point perm -> perm on 14
    out=list(pp)
    for i,L in enumerate(lines):
        img={pp[x] for x in L}; out.append(7+lines.index(img))
    return out
c7=fano_perm([(i+1)%7 for i in range(7)])
m2=fano_perm([(2*i)%7 for i in range(7)])
# a further collineation: find one not in <c7,m2> by brute force
import itertools
def is_coll(pp): return all({pp[x] for x in L} in lines for L in lines)
extra=None
for pp in itertools.permutations(range(7)):
    if pp[0]==0 and pp[1]==1 and is_coll(pp) and pp!=tuple(range(7)): extra=fano_perm(pp); break
PSL32=[c7,m2,extra]
def incid_auto(perm):
    E={(p,7+i) for i,L in enumerate(lines) for p in L}
    E|={(b,a) for a,b in E}
    return all((perm[a],perm[b]) in E for a,b in E)
def find_dual():
    for a in range(7):
      for sgn in (1,-1):
        for b in range(7):
          for sg2 in (1,-1):
            perm=[7+(sgn*p+a)%7 for p in range(7)]+[(sg2*i+b)%7 for i in range(7)]
            if incid_auto(perm): return perm
dual=find_dual()
Heawood=PSL32+[dual]
C14=[cyc(14)]
D14=[cyc(14),[(-i)%14 for i in range(14)]]
# two copies of 7: i and i+7 ; diagonal AGL(1,7) and swap
