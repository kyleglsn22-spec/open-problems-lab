"""Generate Lab/FibWalk/Three/Patterns.lean: the window case analyses behind D_3 = U_3.

A pattern is a window [n, n+g] in which the membership of every n+j in T (T = down or up) is known.
For each pattern we emit
  * core_<T>_<name>: pure real arithmetic. x = δ n, d_j = δ (n+j) = {x + jφ}, threshold facts,
    and same-type shift facts. linarith shows the constraints are contradictory.
  * pat_<T>_<name>: for n ≥ 105, a window with this membership pattern does not exist.
Patterns: 'gap6' (n in T, n+1..n+5 not in T), and every triple (a,b,c) of consecutive gaps
in [1,5] with a+b+c in {9,12,14,15}.
"""
import math
phi = (1 + 5 ** .5) / 2
floor = [math.floor(j * phi) for j in range(20)]
DOWN = [(1, 'θ₂', 'shift_plus1'), (-2, 'θ₃', 'shift_minus2'), (3, 'θ₄', 'shift_plus3'),
        (-5, 'θ₅', 'shift_minus5'), (8, 'θ₆', 'shift_plus8')]
UP = [(-1, 'θ₂', 'up_minus1'), (2, 'θ₃', 'up_plus2'), (-3, 'θ₄', 'up_minus3'),
      (5, 'θ₅', 'up_plus5'), (-8, 'θ₆', 'up_minus8')]

def patterns():
    yield 'gap6', 5, {0}
    for a in range(1, 6):
        for b in range(1, 6):
            for c in range(1, 6):
                if a + b + c in (9, 12, 14, 15):
                    yield f'{a}_{b}_{c}', a + b + c, {0, a, a + b, a + b + c}

def dv(j): return 'x' if j == 0 else f'd{j}'
def pos(j): return 'n' if j == 0 else f'(n + {j})'
def posr(j): return 'n' if j == 0 else f'n + {j}'

def gen(kind, name, g, M):
    T = 'IsDown' if kind == 'D' else 'IsUp'
    shifts = DOWN if kind == 'D' else UP
    hyps, terms = [], []
    hyps.append('(x ' + ' '.join(dv(j) for j in range(1, g + 1)) + ' : ℝ)')
    hyps.append('(hx0 : 0 ≤ x) (hx1 : x < 1)')
    terms.append(' '.join(f'(δ {pos(j)})' for j in range(g + 1)))
    terms.append('(Int.fract_nonneg _) (Int.fract_lt_one _)')
    for j in range(1, g + 1):
        al = f'({j} * φ - {floor[j]})'
        hyps.append(f'(e{j} : d{j} = x + {al} ∨ d{j} = x + {al} - 1) (b{j} : 0 ≤ d{j} ∧ d{j} < 1)')
        terms.append(f'(by have := delta_add n {j} {floor[j]} (by norm_num; linarith) (by norm_num; linarith); '
                     f'push_cast at this; exact this)')
        terms.append('⟨Int.fract_nonneg _, Int.fract_lt_one _⟩')
    for j in range(g + 1):
        mem = j in M
        if (kind == 'D') == mem:
            hyps.append(f'(t{j} : {dv(j)} < ρ)')
        else:
            hyps.append(f'(t{j} : η < {dv(j)})')
        if kind == 'D':
            terms.append(f'M{j}.delta_lt' if mem else f'(isUp_of_not_isDown (by omega) N{j}).lt_delta')
        else:
            terms.append(f'M{j}.lt_delta' if mem else f'(isDown_of_not_isUp (by omega) N{j}).delta_lt')
    cnt = 0
    for p in sorted(M):
        for s, th, lem in shifts:
            q = p + s
            if 0 <= q <= g and q not in M:
                cnt += 1
                if kind == 'D':
                    hyps.append(f'(s{p}_{q} : {dv(p)} < {th})')
                else:
                    hyps.append(f'(s{p}_{q} : 1 - {th} < {dv(p)})')
                lhs = f'{posr(p)} + {s}' if s > 0 else f'{posr(p)} - {-s}'
                terms.append(f'(lt_of_not_ge fun hθ => N{q} (by have hh := {lem} (N := {posr(p)}) (by omega) M{p} hθ; '
                             f'rwa [show {lhs} = {posr(q)} by omega] at hh))')
    L = []
    L.append(f'/-- Real-arithmetic core of the {"down" if kind == "D" else "up"} window `{name}`. -/')
    L.append(f'theorem core_{kind}_{name} ' + '\n    '.join(hyps) + ' : False := by')
    L.append('  have hp := phi_bounds')
    L.append('  simp only [ρ, η, θ₂, θ₃, θ₄, θ₅, θ₆] at *')
    L.append('  obtain ⟨hp1, hp2⟩ := hp')
    for j in range(1, g + 1):
        L.append(f'  obtain ⟨b{j}l, b{j}r⟩ := b{j}')
    chain = ' <;>\n    '.join(f'rcases e{j} with e{j} | e{j} <;> subst e{j} <;> (try linarith)' for j in range(1, g + 1))
    L.append('  ' + chain)
    L.append('')
    memb = ' ∨ '.join(f'j = {m}' for m in sorted(M))
    L.append(f'/-- No window `[n, n + {g}]`, `n ≥ 105`, has `{T}`-pattern `{name}` (members at '
             f'offsets {sorted(M)}). -/')
    L.append(f'theorem pat_{kind}_{name} (n : ℕ) (hn : 105 ≤ n)\n'
             f'    (h : ∀ j ≤ {g}, ({T} (n + j) ↔ {memb})) : False := by')
    L.append('  have hp := phi_bounds')
    for j in range(g + 1):
        if j in M:
            if j == 0:
                L.append(f'  have M0 : {T} n := by simpa using (h 0 (by norm_num)).2 (by norm_num)')
            else:
                L.append(f'  have M{j} : {T} (n + {j}) := (h {j} (by norm_num)).2 (by norm_num)')
        else:
            L.append(f'  have N{j} : ¬ {T} (n + {j}) := fun hh => absurd ((h {j} (by norm_num)).1 hh) (by norm_num)')
    L.append(f'  exact core_{kind}_{name}\n    ' + '\n    '.join(terms))
    L.append('')
    return '\n'.join(L), cnt

out = ['import Lab.FibWalk.Three.Shifts', '',
       '/-!', '# Window case analyses behind `D₃ = U₃`', '',
       'Generated by `explorer/fib-walk/gen_three.py`. For `T` = down or up, a *pattern* fixes which of',
       '`n, n+1, …, n+g` lie in `T`. Each `pat_T_*` shows that for `n ≥ 105` no window has that pattern.',
       'The proof writes `x = δ n` and `d_j = δ (n+j) = {x + jφ}`, and uses three kinds of facts:',
       'the threshold facts (`δ < ρ` for down-integers, `δ > η` for up-integers), and the shift lemmas',
       'for the same type (`Main.lean` for down, `Three/Shifts.lean` for up). Then `linarith` closes',
       'every case of the interval split of `x`. Patterns: `gap6` (no member among `n+1..n+5`), and each',
       'triple `(a,b,c)` of consecutive gaps in `[1,5]` with `a+b+c ∈ {9,12,14,15}`.',
       '-/', '', 'namespace OpenProblemsLab.FibWalk', '', 'open Real',
       'open scoped goldenRatio Classical', '']
out.insert(out.index('namespace OpenProblemsLab.FibWalk'),
           '-- Generated proofs: silence style linters (unused hypotheses, unreachable tactic branches).\n'
           'set_option linter.unusedVariables false\nset_option linter.unusedSimpArgs false\n'
           'set_option linter.unnecessarySeqFocus false\nset_option linter.unusedTactic false\n'
           'set_option linter.unreachableTactic false\n')
for kind in 'DU':
    body = list(out)
    body[3] = body[3] + (' (down-integers)' if kind == 'D' else ' (up-integers)')
    for name, g, M in patterns():
        s, c = gen(kind, name, g, M)
        body.append(s)
    body.append('end OpenProblemsLab.FibWalk')
    open(f'/home/user/open-problems-lab/Lab/FibWalk/Three/Patterns{kind}.lean', 'w').write('\n'.join(body) + '\n')
