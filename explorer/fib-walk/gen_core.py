"""Generate Lab/FibWalk/Core.lean: the finite real-arithmetic case analysis behind 9 ∉ D_4.

Positions j = 0..9 of a window [n, n+9]; d_j = δ(n+j) = {x + jφ}, x = δ(n).
Shifts (Basic.lean): +1 (θ₂), -2 (θ₃), +3 (θ₄), -5 (θ₅), +8 (θ₆).
"""
floors = [0, 1, 3, 4, 6, 8, 9, 11, 12, 14]  # ⌊jφ⌋
shifts = [(1, 'θ₂'), (-2, 'θ₃'), (3, 'θ₄'), (-5, 'θ₅'), (8, 'θ₆')]

def d(j):
    return 'x' if j == 0 else f'd{j}'

def alpha(j):
    return f'({j} * φ - {floors[j]})'

L = []
L.append('import Lab.FibWalk.Basic\n')
L.append('''/-!
# The finite case analysis behind `9 ∉ D₄`

Generated by `explorer/fib-walk/gen_core.py`. Inside a window `[n, n+9]` write `x = δ n` and
`d_j = δ (n+j) = {x + jφ}`, and let `D_j` say that `n + j` is a down-integer. Down-integers have
`δ < ρ`, up-integers have `δ > η`, and the shift lemmas of `Basic.lean` say that a down-integer
`n + p` with `δ ≥ θ` forces `n + p + s` to be a down-integer. `core` shows that these constraints
leave no room for `n` and `n + 9` to be down-integers with exactly three down-integers strictly
between them. The proof splits `x` into the ten intervals on which every `d_j` is an explicit
linear function of `x`, then runs through the `2^8` patterns; `linarith` closes every case.
-/

namespace OpenProblemsLab.FibWalk

open Real
open scoped goldenRatio Classical
''')
args = ['(x ' + ' '.join(f'd{j}' for j in range(1, 10)) + ' : ℝ)',
        '(' + ' '.join(f'D{j}' for j in range(1, 9)) + ' : Prop)',
        '(hx0 : 0 ≤ x) (hx : x < ρ) (hd9 : d9 < ρ)']
for j in range(1, 10):
    args.append(f'(e{j} : d{j} = x + {alpha(j)} ∨ d{j} = x + {alpha(j)} - 1)')
    args.append(f'(b{j} : 0 ≤ d{j} ∧ d{j} < 1)')
for j in range(1, 9):
    args.append(f'(hD{j} : D{j} → d{j} < ρ) (hU{j} : ¬ D{j} → η < d{j})')
hs = []
for p in range(10):
    for s, th in shifts:
        q = p + s
        if 1 <= q <= 8:
            name = f'hS{p}_{q}'
            if p in (0, 9):
                args.append(f'({name} : ¬ D{q} → {d(p)} < {th})')
            else:
                args.append(f'({name} : D{p} → ¬ D{q} → {d(p)} < {th})')
            hs.append(name)
cnt = ' + '.join(f'(if D{j} then 1 else 0)' for j in range(1, 9))
args.append(f'(hc : {cnt} = 3)')
L.append('set_option maxHeartbeats 4000000 in')
L.append('/-- The case analysis: no window `[n, n+9]` with `n`, `n + 9` down and exactly three\n'
         'down-integers strictly between them is compatible with the constraints. -/')
L.append('theorem core ' + '\n    '.join(args) + ' : False := by')
L.append('  have hp := phi_bounds')
L.append('  simp only [ρ, η, θ₂, θ₃, θ₄, θ₅, θ₆] at *')
L.append('  obtain ⟨hp1, hp2⟩ := hp')
for j in range(1, 10):
    L.append(f'  obtain ⟨b{j}l, b{j}r⟩ := b{j}')
for j in range(1, 10):
    L.append(f'  rcases e{j} with e{j} | e{j} <;> subst e{j} <;> (try linarith) <;>')
bc = ' <;>\n    '.join(f'by_cases h{j} : D{j}' for j in range(1, 9))
L.append('  (' + bc + ' <;>')
hl = ', '.join(f'h{j}' for j in range(1, 9))
L.append(f'    simp only [{hl}, if_true, if_false] at hc <;> norm_num at hc <;>')
L.append(f'    simp only [{hl}, not_true_eq_false, not_false_eq_true,')
L.append('      IsEmpty.forall_iff, forall_const] at * <;>')
L.append('    linarith)')
L.append('\nend OpenProblemsLab.FibWalk')
open('/home/user/open-problems-lab/Lab/FibWalk/Core.lean', 'w').write('\n'.join(L) + '\n')
print(len(hs), 'shift hypotheses')
